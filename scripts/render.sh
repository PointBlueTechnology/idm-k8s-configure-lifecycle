#!/usr/bin/env bash
# Render Job/RBAC manifests from manifests/templates using config/site.env
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SITE="${SITE_ENV:-$ROOT/config/site.env}"
OUT="${RENDER_OUT:-$ROOT/manifests/rendered}"

if [ ! -f "$SITE" ]; then
  echo "ERROR: missing $SITE — copy config/site.env.example to config/site.env and fill values" >&2
  exit 1
fi

# shellcheck disable=SC1090
set -a
# strip comments/blank for sourcing
# shellcheck source=/dev/null
source "$SITE"
set +a

: "${NAMESPACE:?}"
: "${LIFECYCLE_NAME:?}"
: "${PUBLIC_HOST:?}"
: "${PUBLIC_BASE_URL:?}"
: "${ENGINE_HOST:?}"
: "${ENGINE_IP:?}"
: "${PG_HOST:?}"
: "${SHARED_PVC_NAME:?}"
: "${IMAGE_UA:?}"
: "${UA_DEPLOYMENT_NAME:?}"
: "${COMMON_PASSWORD_SECRET:?}"
: "${KEYSTORE_SECRET:?}"

# Defaults for optional knobs
export PG_PORT="${PG_PORT:-5432}"
export INGRESS_IP="${INGRESS_IP:-}"
export IMAGE_PULL_POLICY="${IMAGE_PULL_POLICY:-IfNotPresent}"
export SMOKE_IMAGE="${SMOKE_IMAGE:-curlimages/curl:8.5.0}"
export SHARED_CONFIG="${SHARED_CONFIG:-/config}"
export LIFECYCLE_LIB="${LIFECYCLE_LIB:-/lifecycle/lib/idm-lifecycle-lib.jar}"
export COMMON_PASSWORD_KEY="${COMMON_PASSWORD_KEY:-password}"
export KEYSTORE_SECRET_KEY="${KEYSTORE_SECRET_KEY:-keystore-pwd}"
export VAULT_ADMIN_DN="${VAULT_ADMIN_DN:-cn=admin,ou=sa,o=system}"
export UA_ADMIN_DN="${UA_ADMIN_DN:-cn=uaadmin,ou=sa,o=data}"
export UA_DRIVER_DN="${UA_DRIVER_DN:-cn=User Application Driver,cn=driverset1,o=system}"
export UA_DRIVER_CN="${UA_DRIVER_CN:-User Application Driver}"
export DRIVERSET_DN="${DRIVERSET_DN:-cn=driverset1,o=system}"
export USER_CONTAINER="${USER_CONTAINER:-o=data}"
export USER_ROOT_CONTAINER="${USER_ROOT_CONTAINER:-ou=users,o=data}"
export GROUP_ROOT_CONTAINER="${GROUP_ROOT_CONTAINER:-ou=groups,o=data}"
export ADMIN_CONTAINER="${ADMIN_CONTAINER:-ou=sa,o=data}"
export LDAP_PORT="${LDAP_PORT:-389}"
export LDAPS_PORT="${LDAPS_PORT:-636}"
export UA_DB_NAME="${UA_DB_NAME:-idmuserappdb}"
export WFE_DB_NAME="${WFE_DB_NAME:-igaworkflowdb}"
export UA_WFE_DATABASE_USER="${UA_WFE_DATABASE_USER:-idmadmin}"
export UA_APP_CTX="${UA_APP_CTX:-IDMProv}"
export FORMRENDERER_CONFIG_DIR="${FORMRENDERER_CONFIG_DIR:-/config/FormRenderer}"
export WFE_APP_CTX="${WFE_APP_CTX:-workflow}"
export LIQUIBASE_CONTEXTS="${LIQUIBASE_CONTEXTS:-prov,newdb,updatedb}"
export RESET_ISM="${RESET_ISM:-1}"

# eDirectory backup CronJob. INCLUDE_NICI defaults true (full DIB + NICI via dsbk -e).
export BACKUP_SCHEDULE="${BACKUP_SCHEDULE:-0 2 * * *}"
export BACKUP_TIMEZONE="${BACKUP_TIMEZONE:-UTC}"
export BACKUP_PVC_NAME="${BACKUP_PVC_NAME:-idm-vault-backup}"
export BACKUP_DEST="${BACKUP_DEST:-/backups/edir}"
export BACKUP_PREFIX="${BACKUP_PREFIX:-edir}"
export BACKUP_RETENTION_COUNT="${BACKUP_RETENTION_COUNT:-14}"
export BACKUP_RETENTION_DAYS="${BACKUP_RETENTION_DAYS:-0}"
export BACKUP_ACTIVE_DEADLINE_SECONDS="${BACKUP_ACTIVE_DEADLINE_SECONDS:-7200}"
export BACKUP_FS_GROUP="${BACKUP_FS_GROUP:-0}"
export IMAGE_VAULT_BACKUP="${IMAGE_VAULT_BACKUP:-edir-backup:local}"
export INCLUDE_NICI="${INCLUDE_NICI:-true}"
export INCLUDE_STREAMS="${INCLUDE_STREAMS:-true}"
export INCLUDE_NDS_CONF="${INCLUDE_NDS_CONF:-true}"
export NICI_BACKUP_SECRET="${NICI_BACKUP_SECRET:-idm-nici-backup}"
export NICI_BACKUP_SECRET_KEY="${NICI_BACKUP_SECRET_KEY:-password}"
export VAULT_TARGET="${VAULT_TARGET:-standalone}"
export VAULT_WORKLOAD_KIND="${VAULT_WORKLOAD_KIND:-}"
export VAULT_WORKLOAD_NAME="${VAULT_WORKLOAD_NAME:-}"
export VAULT_DOCKER_SUDO="${VAULT_DOCKER_SUDO:-false}"
export VAULT_SSH_HOST="${VAULT_SSH_HOST:-$ENGINE_IP}"
export VAULT_SSH_PORT="${VAULT_SSH_PORT:-22}"
export VAULT_SSH_USER="${VAULT_SSH_USER:-backup}"
export VAULT_SSH_SECRET="${VAULT_SSH_SECRET:-idm-vault-ssh}"
export VAULT_SSH_SECRET_KEY="${VAULT_SSH_SECRET_KEY:-ssh-privatekey}"
export VAULT_SSH_KNOWN_HOSTS_KEY="${VAULT_SSH_KNOWN_HOSTS_KEY:-known_hosts}"
export VAULT_SSH_STRICT_HOST_KEY="${VAULT_SSH_STRICT_HOST_KEY:-yes}"
export VAULT_DOCKER_BIN="${VAULT_DOCKER_BIN:-docker}"
export VAULT_DOCKER_CONTAINER="${VAULT_DOCKER_CONTAINER:-engine-container}"
export VAULT_EXEC_USER="${VAULT_EXEC_USER:-}"
export VAULT_POD_NAME="${VAULT_POD_NAME:-}"
export VAULT_POD_LABEL_SELECTOR="${VAULT_POD_LABEL_SELECTOR:-}"
export VAULT_SERVICE_NAME="${VAULT_SERVICE_NAME:-}"
export VAULT_POD_NAMESPACE="${VAULT_POD_NAMESPACE:-$NAMESPACE}"
export VAULT_POD_CONTAINER="${VAULT_POD_CONTAINER:-}"
export VAULT_NDS_CONF="${VAULT_NDS_CONF:-/etc/opt/novell/eDirectory/conf/nds.conf}"
export VAULT_STAGING_DIR="${VAULT_STAGING_DIR:-/tmp/idm-edir-backup}"
export VAULT_DSBK_BIN="${VAULT_DSBK_BIN:-dsbk}"

mkdir -p "$OUT"
# shellcheck disable=SC2016 # envsubst wants a literal list of $VAR names
VARS='$NAMESPACE $LIFECYCLE_NAME $PUBLIC_HOST $PUBLIC_BASE_URL $INGRESS_IP $ENGINE_HOST $ENGINE_IP $PG_HOST $PG_PORT $SHARED_PVC_NAME $UA_DEPLOYMENT_NAME $IMAGE_UA $IMAGE_PULL_POLICY $SMOKE_IMAGE $COMMON_PASSWORD_SECRET $COMMON_PASSWORD_KEY $KEYSTORE_SECRET $KEYSTORE_SECRET_KEY $SHARED_CONFIG $LIFECYCLE_LIB $VAULT_ADMIN_DN $UA_ADMIN_DN $UA_DRIVER_DN $UA_DRIVER_CN $DRIVERSET_DN $USER_CONTAINER $USER_ROOT_CONTAINER $GROUP_ROOT_CONTAINER $ADMIN_CONTAINER $LDAP_PORT $LDAPS_PORT $UA_DB_NAME $WFE_DB_NAME $UA_WFE_DATABASE_USER $UA_APP_CTX $WFE_APP_CTX $LIQUIBASE_CONTEXTS $RESET_ISM $FORMRENDERER_CONFIG_DIR $BACKUP_SCHEDULE $BACKUP_TIMEZONE $BACKUP_PVC_NAME $BACKUP_DEST $BACKUP_PREFIX $BACKUP_RETENTION_COUNT $BACKUP_RETENTION_DAYS $BACKUP_ACTIVE_DEADLINE_SECONDS $BACKUP_FS_GROUP $IMAGE_VAULT_BACKUP $INCLUDE_NICI $INCLUDE_STREAMS $INCLUDE_NDS_CONF $NICI_BACKUP_SECRET $NICI_BACKUP_SECRET_KEY $VAULT_TARGET $VAULT_WORKLOAD_KIND $VAULT_WORKLOAD_NAME $VAULT_DOCKER_SUDO $VAULT_SSH_HOST $VAULT_SSH_PORT $VAULT_SSH_USER $VAULT_SSH_SECRET $VAULT_SSH_SECRET_KEY $VAULT_SSH_KNOWN_HOSTS_KEY $VAULT_SSH_STRICT_HOST_KEY $VAULT_DOCKER_BIN $VAULT_DOCKER_CONTAINER $VAULT_EXEC_USER $VAULT_POD_NAME $VAULT_POD_LABEL_SELECTOR $VAULT_SERVICE_NAME $VAULT_POD_NAMESPACE $VAULT_POD_CONTAINER $VAULT_NDS_CONF $VAULT_STAGING_DIR $VAULT_DSBK_BIN'

for f in "$ROOT"/manifests/templates/*.yaml; do
  base="$(basename "$f")"
  envsubst "$VARS" < "$f" > "$OUT/$base"
done

echo "Rendered manifests → $OUT"
ls -1 "$OUT"
